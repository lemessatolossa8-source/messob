function isPlainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

export function mergeSiteSettings(base = DEFAULT_SITE_SETTINGS, override = {}) {
  if (!isPlainObject(base)) return override;
  const source = isPlainObject(override) ? override : {};
  const out = { ...base };

  for (const key of Object.keys(base)) {
    if (!(key in source) || source[key] === undefined) continue;
    if (isPlainObject(base[key]) && isPlainObject(source[key])) {
      out[key] = mergeSiteSettings(base[key], source[key]);
    } else if (isPlainObject(base[key]) && typeof source[key] === "string") {
      out[key] = { ...base[key], en: source[key] };
    } else {
      out[key] = source[key];
    }
  }

  for (const key of Object.keys(source)) {
    if (!(key in out) && source[key] !== undefined) {
      out[key] = source[key];
    }
  }

  return out;
}

export function validateSiteSettings(settings) {
  const errors = [];
  const email = settings?.contactInfo?.email;
  if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(email).trim())) {
    errors.push("Enter a valid contact email address.");
  }
  if (!settings?.contactInfo?.phone || String(settings.contactInfo.phone).trim().length < 8) {
    errors.push("Enter a valid contact phone number.");
  }
  if (!settings?.contactInfo?.address?.en || String(settings.contactInfo.address.en).trim().length < 3) {
    errors.push("Office address (English) is required.");
  }

  const checkUrl = (label, value, { allowRelative = false } = {}) => {
    if (!value || String(value).trim() === "") return;
    const raw = String(value).trim();
    if (allowRelative && raw.startsWith("/")) return;
    try {
      const url = new URL(raw);
      if (!["http:", "https:"].includes(url.protocol)) {
        errors.push(`${label} must start with http:// or https://`);
      }
    } catch {
      errors.push(`${label} must be a valid URL.`);
    }
  };

  checkUrl("Facebook URL", settings?.socialMedia?.facebook);
  checkUrl("Twitter URL", settings?.socialMedia?.twitter);
  checkUrl("YouTube URL", settings?.socialMedia?.youtube);
  checkUrl("Telegram URL", settings?.socialMedia?.telegram);
  checkUrl("LinkedIn URL", settings?.socialMedia?.linkedin);
  checkUrl("E-Land URL", settings?.eService?.eLand?.url);
  checkUrl("E-Conference URL", settings?.eService?.eConference?.url);
  checkUrl("E-Library URL", settings?.eService?.eLibrary?.url);
  checkUrl("E-Trade URL", settings?.eService?.eTrade?.url);
  checkUrl("Social preview image", settings?.seo?.ogImage, { allowRelative: true });

  if (!["om", "am", "en"].includes(settings?.languageSettings?.defaultLanguage)) {
    errors.push("Default language must be Afan Oromo, Amharic, or English.");
  }

  const perPage = Number(settings?.contentSettings?.itemsPerPage);
  if (!Number.isInteger(perPage) || perPage < 6 || perPage > 50) {
    errors.push("Items per page must be between 6 and 50.");
  }

  return errors;
}
